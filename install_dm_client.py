print("""
============================================================
达梦数据库客户端 SDK 安装指南
============================================================

问题: dmPython �要达梦数据库客户端库 (DLL) 才能工作

解决方案:

方法1: 从达梦官网下载客户端 SDK
--------------------------------
1. 访问达梦官网: https://www.dameng.com/
2. 进入"下载中心" -> "客户端"
3. 下载对应的 Windows 客户端 SDK
4. 解压后，将 bin 目录下的 DLL 文件复制到 Python 的 DLLs 目录

方法2: 复制 DLL 文件
--------------------------------
找到达梦数据库安装目录，通常在:
  C:\\dmdbms\\bin

需要复制以下 DLL 文件到 Python 的 DLLs 目录:
  - dmdpi.dll
  - dmCrypto.dll
  (可能还需要其他依赖 DLL)

Python DLLs 目录通常在:
  C:\\Python312\\DLLs\\
  或
  C:\\Users\\<用户>\\AppData\\Local\\Programs\\Python\\Python312\\DLLs\\

方法3: 添加到系统 PATH
--------------------------------
将达梦的 bin 目录添加到系统环境变量 PATH:
  1. 右键"此电脑" -> "属性" -> "高级系统设置"
  2. "环境变量" -> 系统变量 -> Path -> 编辑
  3. 添加: C:\\dmdbms\\bin
  4. 重启命令行窗口

方法4: 使用临时 PATH (用于测试)
--------------------------------
在命令行中临时设置:
  set PATH=C:\\dmdbms\\bin;%PATH%
  python test_connection.py

============================================================

安装完成后，运行测试:
  python test_connection.py

============================================================
""")
